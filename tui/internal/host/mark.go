// 점 하나가 어느 비트인지. 점자는 왼칸 위에서 아래로 1·2·3, 오른칸이
// 4·5·6, 그리고 아래 두 줄이 7·8 이다.
var markDotBit = [2][4]rune{
	{0x01, 0x02, 0x04, 0x40},
	{0x08, 0x10, 0x20, 0x80},
}

// renderMark 는 픽셀 그림을 점자로 옮긴다. 한 칸이 가로 2 × 세로 4 픽셀이다.
func renderMark(px []string) []string {
	on := func(y, x int) bool {
		return y < len(px) && x < len(px[y]) && px[y][x] == '#'
	}
	width := 0
	for _, row := range px {
		width = style.Max(width, len(row))
	}

	out := make([]string, (len(px)+3)/4)
	for r := range out {
		var b strings.Builder
		for c := 0; c < (width+1)/2; c++ {
			var cell rune
			for dx := 0; dx < 2; dx++ {
				for dy := 0; dy < 4; dy++ {
					if on(4*r+dy, 2*c+dx) {
						cell |= markDotBit[dx][dy]
					}
				}
			}
			b.WriteRune(0x2800 + cell)
		}
		out[r] = b.String()
	}
	return out
}

