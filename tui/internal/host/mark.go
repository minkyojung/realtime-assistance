// 마크 — 첫 화면 박스의 왼쪽에 서는 작은 음표.
//
// 이름표(home.go)가 이름을 말하고, 이것은 그것이 무엇인지를 말한다.
// 둘이 같은 자리에 있으면 하나가 죽으므로, 이름표는 위에 크게 두고
// 마크는 박스 안에 작게 둔다.
//
// **점자로 찍는다.** 한 칸이 2×4 픽셀이라 이름표가 쓰는 반블록(1×2)보다
// 네 배 곱다. 36×31 픽셀 그림이 18칸 × 8줄에 들어가는데, 같은 그림을
// 반블록으로 찍으면 36칸 × 16줄이라 박스 안에서 마크가 아니라 두 번째
// 이름표가 된다.
//
// 획은 기둥 3픽셀, 빔 5픽셀이다. 이름표가 12픽셀 높이에 2픽셀 획이니
// 비율로는 그보다 훨씬 가늘다 — 이름이 크게 말하는 자리이므로 마크는
// 옆에서 조용해야 한다. 머리는 타원이라 획보다 굵고, 그 대비가 음표를
// 음표로 읽히게 한다.
//
// 점자를 꺼리는 이유가 하나 있다 — 터미널과 글꼴에 따라 되다 안 되다
// 하는 문자는 없는 것만 못하다(docs/07 2절, style/artwork.go). 다만 이
// 제품은 Music.app 을 AppleScript 로 부르므로 macOS 밖에서는 아예 돌지
// 않고, macOS 의 기본 고정폭 글꼴(SF Mono·Menlo)은 U+2800 블록을 전부
